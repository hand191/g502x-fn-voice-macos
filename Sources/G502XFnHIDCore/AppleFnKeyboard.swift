import Foundation

public enum AppleFnKeyboard {
    public static let reportLength = 8

    // Adapted from Apple's CoreHID virtual-keyboard sample. See
    // THIRD_PARTY_NOTICES.md for the applicable Apple Sample Code License.
    // The final input field is vendor usage-page 0xff, usage 0x03: Apple Fn.
    public static let reportDescriptor = Data([
        0x05, 0x01, 0x09, 0x06, 0xa1, 0x01,
        0x05, 0x07, 0x19, 0xe0, 0x29, 0xe7,
        0x15, 0x00, 0x25, 0x01, 0x75, 0x01,
        0x95, 0x08, 0x81, 0x02,
        0x95, 0x01, 0x75, 0x08, 0x81, 0x01,
        0x05, 0x08, 0x19, 0x01, 0x29, 0x05,
        0x95, 0x05, 0x75, 0x01, 0x91, 0x02,
        0x95, 0x01, 0x75, 0x03, 0x91, 0x01,
        0x05, 0x07, 0x19, 0x00, 0x2a, 0xff, 0x00,
        0x95, 0x05, 0x75, 0x08, 0x15, 0x00,
        0x26, 0xff, 0x00, 0x81, 0x00,
        0x05, 0xff, 0x09, 0x03, 0x75, 0x08,
        0x95, 0x01, 0x81, 0x02, 0xc0,
    ])

    public static func inputReport(fnPressed: Bool) -> Data {
        var bytes = [UInt8](repeating: 0, count: reportLength)
        bytes[reportLength - 1] = fnPressed ? 1 : 0
        return Data(bytes)
    }

}
